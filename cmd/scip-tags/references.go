package main

import (
	"encoding/json"
	"flag"
	"os"
	"path/filepath"

	"github.com/danilrwx/scip-tags/tags"
)

func runReferences(args []string) error {
	flags := flag.NewFlagSet("scip-tags refs", flag.ExitOnError)
	index := flags.String("tags", "tags", "path to a tags file generated by scip-tags")
	file := flags.String("file", "", "source path relative to the tags file")
	line := flags.Int("line", 0, "source line, starting at 1")
	column := flags.Int("column", 0, "source byte column, starting at 1")
	hash := flags.String("sourcehash", "", "hash of the current source line")

	if err := flags.Parse(args); err != nil {
		return err
	}

	input, err := os.Open(*index)
	if err != nil {
		return err
	}
	defer func() { _ = input.Close() }()

	root, err := os.OpenRoot(filepath.Dir(*index))
	if err != nil {
		return err
	}
	defer func() { _ = root.Close() }()

	result, err := tags.References(input, root.FS(), tags.Position{Path: *file, Line: *line, Column: *column}, *hash)
	if err != nil {
		return err
	}

	return json.NewEncoder(os.Stdout).Encode(result)
}
